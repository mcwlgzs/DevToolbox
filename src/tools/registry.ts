export const TOOLS: readonly ToolMeta[] = [HOME_TOOL, ...TOOL_ENTRIES]

function normalizePath(pathname: string): string {
  const clean = pathname.split('?')[0].split('#')[0]
  return clean.endsWith('/') ? clean : `${clean}/`
}

/** 精确匹配路由；未知路径返回 undefined（用于渲染 404）。 */
export function findTool(pathname: string): ToolMeta | undefined {
  const normalized = normalizePath(pathname)
  return TOOLS.find((tool) => tool.path === normalized)
}

/** 规范化任意路径：未知路径回落到首页。 */
export function resolveTool(pathname: string): ToolMeta {
  return findTool(pathname) ?? HOME_TOOL
}

/** 生成工具的绝对 URL（用于 canonical / sitemap）。 */
export function toolUrl(tool: ToolMeta, siteUrl: string): string {
  const base = siteUrl.replace(/\/+$/, '')
  return tool.slug ? `${base}/${tool.slug}/` : `${base}/`
}
